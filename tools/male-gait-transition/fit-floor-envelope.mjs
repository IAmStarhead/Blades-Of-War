// Reproduce the small anticipatory lift envelope for this exact GLB.
// The runtime still measures the actual selected soles and uses the larger of
// this envelope and the immediate floor correction. This table spreads tiny
// corrections over nearby gait phases to avoid a sharp vertical root flick.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import {NodeIO} from '../male-library-motion/node_modules/@gltf-transform/core/dist/index.js';
import {makeEvaluator} from '../male-motion-fit/pose.mjs';
import {RUN_PHASE_OFFSET, wrapPhase} from './phase-clock.mjs';
const here = path.dirname(fileURLToPath(import.meta.url)), repo = path.resolve(here, '../..');
const source = path.join(repo, 'work/male-hand-flight/male_hands_airfoot_trial.glb');
const bytes = fs.readFileSync(source);
assert.equal(createHash('sha256').update(bytes).digest('hex'), '576077e068f2c48a88c208be0ad72b4214e42164d1e5b0f0f9f7050f3967e2bf');
const root = (await new NodeIO().read(source)).getRoot();
const walk = makeEvaluator(root, 'NewBody', 'Walk_Game_Trial'), run = makeEvaluator(root, 'NewBody', 'Run_Game_Trial');
const mixed = makeEvaluator(root, 'NewBody', 'Walk_Game_Trial');
const N = 1024, weights = 64, radius = Math.round(.04 * N), safety = 1.05;
function required(phase, weight) {
  walk.pose(phase * walk.duration); run.pose(wrapPhase(phase + RUN_PHASE_OFFSET) * run.duration);
  for (const [name, dest] of mixed.bones) {
    const a = walk.bones.get(name), b = run.bones.get(name);
    dest.position.lerpVectors(a.position, b.position, weight);
    dest.quaternion.slerpQuaternions(a.quaternion, b.quaternion, weight).normalize();
  }
  mixed.updateMatrices();
  const x = .002 - Math.min(...mixed.currentLows());
  return x <= 0 ? 0 : x < .002 ? x * x / .004 : x - .001;
}
const raw = Array.from({length: N}, (_, i) => {
  let max = 0;
  for (let j = 1; j < weights; j++) {
    const w = j / weights; max = Math.max(max, required(i / N, w) / (4 * w * (1 - w)));
  }
  return max;
});
// Circular max dilation followed by a positive raised-cosine smoothing kernel.
// Each smoothed sample includes the original phase in all dilated windows.
const dilated = raw.map((_, i) => {
  let max = 0; for (let j = -radius; j <= radius; j++) max = Math.max(max, raw[(i + j + N) % N]); return max;
});
const envelope = dilated.map((_, i) => {
  let sum = 0, total = 0;
  for (let j = -radius; j <= radius; j++) {
    const weight = .5 + .5 * Math.cos(Math.PI * j / (radius + 1));
    sum += dilated[(i + j + N) % N] * weight; total += weight;
  }
  return sum / total * safety;
});
const rows = [];
for (let i = 0; i < N; i += 16) rows.push('  ' + envelope.slice(i, i + 16).map(v => v.toFixed(8)).join(', ') + ',');
const output = `// Generated by fit-floor-envelope.mjs for model SHA-256 576077e0…e2bf.\n// 1,024 cyclic phases × 63 interior weights; 0.04-cycle dilation and\n// raised-cosine smoothing, with a 5% margin. Runtime sole measurement is\n// still the safety fallback; pure walk/run receive no envelope lift.\nconst heights = new Float32Array([\n${rows.join('\n')}\n]);\nexport function floorEnvelope(phase, weight) {\n  const p = ((phase % 1) + 1) % 1 * heights.length;\n  const i = Math.floor(p), t = p - i;\n  const height = heights[i] * (1 - t) + heights[(i + 1) % heights.length] * t;\n  return height * 4 * weight * (1 - weight);\n}\n`;
const target = path.join(here, 'floor-envelope.mjs');
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), output, 'Envelope is not reproducible');
else fs.writeFileSync(target, output);
console.log(`${process.argv.includes('--check') ? 'PASS' : 'WROTE'} ${target}; ${N} phases × ${weights - 1} weights, peak envelope ${(Math.max(...envelope) * 1000).toFixed(2)} mm.`);
